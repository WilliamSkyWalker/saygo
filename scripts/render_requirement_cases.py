"""Render reviewable BDD scenarios from independently executable contract rows."""
from pathlib import Path
import importlib.util
import re
import sys
import unittest

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
spec=importlib.util.spec_from_file_location('requirement_cases',ROOT/'tests/control_demo/test_requirements.py')
module=importlib.util.module_from_spec(spec); spec.loader.exec_module(module)
integration_spec=importlib.util.spec_from_file_location('package_cases',ROOT/'tests/control_demo/test_updates_package.py')
integration=importlib.util.module_from_spec(integration_spec); integration_spec.loader.exec_module(integration)
cases=[*module.CASES,*integration.BDD]
requirements=set(re.findall(r'\| ([A-Z]+-\d{3}) \|', (ROOT/'docs/requirements.md').read_text()))
assert len(cases) >= 500
assert len({case['id'] for case in cases}) == len(cases)
assert all(case['requirement'] in requirements for case in cases)
assert len(cases) == sum(unittest.defaultTestLoader.loadTestsFromModule(m).countTestCases()
                         for m in (module, integration))
lines=['# Generated by scripts/render_requirement_cases.py; edit the source cases, then regenerate.',
       '# One Scenario = one independently named unittest. No Scenario Outline count inflation.',
       'Feature: Saygo 全项目需求自动化契约','']
for case in cases:
    lines += [f"  @{case['id']} @{case['requirement']} @auto",
              f"  Scenario: {case['id']} {case['family']}",
              '    Given '+case['given'].replace('\n','\\n'),
              '    When '+case['when'].replace('\n','\\n'),
              '    Then '+case['then'].replace('\n','\\n'),'']
path=ROOT/'docs/testing/requirements.feature'; path.parent.mkdir(parents=True,exist_ok=True)
text='\n'.join(lines)
if '--check' in sys.argv:
    if path.read_text()!=text:raise SystemExit('BDD catalog differs: run scripts/render_requirement_cases.py')
else:path.write_text(text)
print(f'{len(cases)} independent BDD / unittest cases')
